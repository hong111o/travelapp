#!/usr/bin/env node
/* Travel Marvel · build the passport's list of towns and cities
 *
 * The airport list alone only knows cities that have an airport, so
 * Kyoto, Bruges or Sintra could not be picked. This adds every place of
 * at least MIN_POP people from GeoNames (CC BY 4.0), as packaged in the
 * all-the-cities npm package's cities.pbf.
 *
 * The file is read as data with the small decoder below — no code from
 * the package is run.
 *
 *   npm pack all-the-cities@3        → package/cities.pbf
 *   node tools/build-cities-data.js <cities.pbf>
 *
 * Output: data/cities.js, one line per place, biggest first so the
 * suggestions put Paris before Paris, Texas:
 *   name|country|lat|lng
 */
'use strict';

const fs = require('fs');
const path = require('path');

const MIN_POP = 15000;
const src = process.argv[2];
if (!src) { console.error('usage: node tools/build-cities-data.js <cities.pbf>'); process.exit(1); }

const buf = fs.readFileSync(src);
let pos = 0;

function varint() {
  let result = 0, shift = 0, b;
  do {
    b = buf[pos++];
    result += (b & 0x7f) * Math.pow(2, shift);
    shift += 7;
  } while (b & 0x80);
  return result;
}
function svarint() { const n = varint(); return n % 2 ? (n + 1) / -2 : n / 2; }
function str(end) {
  const len = varint();
  const s = buf.toString('utf8', pos, pos + len);
  pos += len;
  return s;
}

/* The file is a run of length-prefixed messages; coordinates are stored
   as deltas from the previous city, in 1e-5 degrees. */
let lon = 0, lat = 0;
const out = [];
while (pos < buf.length) {
  const end = varint() + pos;
  const c = { name: '', country: '', pop: 0 };
  while (pos < end) {
    const key = varint(), tag = Math.floor(key / 8), wire = key % 8;
    if (tag === 2) c.name = str();
    else if (tag === 3) c.country = str();
    else if (tag === 9) c.pop = varint();
    else if (tag === 10) { lon += svarint(); }
    else if (tag === 11) { lat += svarint(); }
    else if (wire === 0) varint();
    else if (wire === 2) { const l = varint(); pos += l; }
    else throw new Error('unexpected wire type ' + wire + ' at ' + pos);
  }
  c.lng = lon / 1e5; c.lat = lat / 1e5;
  if (c.pop >= MIN_POP && c.name && /^[A-Z]{2}$/.test(c.country)) out.push(c);
}

out.sort((a, b) => b.pop - a.pop);
const clean = s => s.replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
const n4 = x => x.toFixed(3).replace(/\.?0+$/, '');
const lines = out.map(c => [clean(c.name), c.country, n4(c.lat), n4(c.lng)].join('|'));

const root = path.resolve(__dirname, '..');
fs.writeFileSync(path.join(root, 'data/cities.js'),
  '/* GENERATED by tools/build-cities-data.js — do not edit.\n' +
  '   Towns and cities of ' + MIN_POP.toLocaleString('en') + '+ people, biggest first: name|country|lat|lng\n' +
  '   Source: GeoNames (CC BY 4.0, https://www.geonames.org/) via all-the-cities — see data/LICENSES.md\n*/\n' +
  'window.TM_CITIES = ' + JSON.stringify(lines.join('\n')) + ';\n');
console.log('✓ data/cities.js  ' + lines.length + ' places, ' +
  (fs.statSync(path.join(root, 'data/cities.js')).size / 1024).toFixed(0) + ' KB');
